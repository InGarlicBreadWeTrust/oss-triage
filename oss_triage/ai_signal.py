"""Pull-request triage heuristics -- the "AI-slop filter".

These heuristics *advise* a human maintainer: they flag PRs that look low-effort,
generic, or possibly AI-generated so a person reviews them closer. They are NOT
verdicts. Every check is labelled and weighted, and the aggregate risk score is
capped so a single signal never forces a "needs review" call on its own.

Nothing here touches the network or the filesystem; it scores a PullRequest (or a
plain dict) and returns a PRVerdict.
"""
from __future__ import annotations
import re
from dataclasses import dataclass, field

from .models import PullRequest, Signal

# Over-indexed phrases on generated / auto-written PRs. Kept small and obvious so
# we never accuse a real human -- only surface "look closer".
_AI_TELL = [
    "sure,", "certainly", "absolutely", "i hope this helps",
    "as requested", "i've updated", "i have updated", "here is the pull",
    "here's the pull", "as discussed, i've", "please find attached",
    "i made the changes", "i made the update", "regards, the assistant",
    "generated by", "auto-generated", "automated pull",
]
_RE_AI = re.compile("|".join(re.escape(p) for p in _AI_TELL), re.IGNORECASE)

# Titles that say nothing about what the change does.
_GENERIC_TITLE = re.compile(
    r"^(fix|fixed|fixing|update|updated|improve|improved|improvement|"
    r"cleanup|clean ?up|minor|wip|misc|miscellaneous|bug ?fix|address)"
    r"(:|\b.*)?$",
    re.IGNORECASE,
)

# A body referencing an issue/closing ref: "#123", "Fixes #123", "closes #4".
_RE_ISSUE_REF = re.compile(r"#\d+")

# Threshold above which a PR is surfaced for human review.
_REVIEW_THRESHOLD = 50.0


def _clamp(x: float, lo: float = 0.0, hi: float = 100.0) -> float:
    return max(lo, min(hi, x))


@dataclass
class PRVerdict:
    number: int
    title: str
    html_url: str
    risk: float
    needs_review: bool
    signals: list = field(default_factory=list)
    first_time: bool = False
    reason: str = ""

    def as_dict(self) -> dict:
        return {
            "number": self.number,
            "title": self.title,
            "html_url": self.html_url,
            "risk": round(self.risk, 1),
            "needs_review": self.needs_review,
            "first_time": self.first_time,
            "reason": self.reason,
            "signals": [s.as_row() for s in self.signals],
        }


def pr_signals(pr: PullRequest) -> list:
    """Weighted signals that a PR is low-effort / generic / possibly generated.

    All weights are positive and add up to a risk score in [0, 100].
    """
    sigs: list = []
    body = (pr.body or "")
    title = (pr.title or "").strip()
    changed = pr.changed_files
    lines = pr.lines_changed

    # 1. No or very short description on a non-trivial change.
    if changed > 0 and (not body or len(body.strip()) < 40):
        sigs.append(Signal(
            "no-description", 14.0,
            "non-trivial change with little or no explanation"))
    elif changed > 0:
        sigs.append(Signal("has-description", -10.0,
            "PR body explains the change"))

    # 2. A code change with no test touched.
    if changed >= 1 and not pr.has_tests:
        sigs.append(Signal("no-tests", 16.0,
            "touches files but no test was added or updated"))
    elif pr.has_tests:
        sigs.append(Signal("has-tests", -8.0, "touched a test file"))

    # 3. A very large surface area is suspicious absent an explanation.
    if changed > 30:
        sigs.append(Signal("huge-diff", 12.0,
            f"{changed} files changed -- unusually broad for one PR"))
    elif 3 <= changed <= 25:
        sigs.append(Signal("scoped-diff", -4.0,
            "change is reasonably scoped"))

    # 4. Generic / uninformative title with no issue link.
    if _GENERIC_TITLE.match(title) and lines < 80 and not _RE_ISSUE_REF.search(body):
        sigs.append(Signal("generic-title", 10.0,
            f"title '{title or '(empty)'}' says nothing about the change"))

    # 5. No link back to the issue it claims to fix.
    if changed > 2 and not _RE_ISSUE_REF.search(body + " " + title):
        sigs.append(Signal("no-issue-link", 6.0,
            "no reference to the issue this addresses"))

    # 6. Tell-tale generated / auto-written prose.
    m = _RE_AI.search(body)
    if m:
        sigs.append(Signal("ai-tell", 12.0,
            f"body reads like generated prose (matched '{m.group(0).strip()}')"))

    # 7. First-time contributor: cheap extra eyes.
    if pr.first_time:
        sigs.append(Signal("first-time", 8.0,
            "first-time contributor -- worth a closer look"))

    return sigs


def _reason(needs: bool, threshold: float, pos: float, neg: float) -> str:
    if needs:
        return (f"risk {pos:.0f} exceeds review threshold "
                f"({threshold:.0f}); net of mitigations {neg:+.0f}. "
                "Surface for human triage -- a heuristic, not a verdict.")
    return (f"risk below threshold ({threshold:.0f}); "
            f"mitigations {neg:+.0f} offset concerns. Route normally.")


def triage_pr(pr: PullRequest, threshold: float = _REVIEW_THRESHOLD
                ) -> PRVerdict:
    """Return a PRVerdict; needs_review when risk >= threshold.

    risk = sum of positive weights, cap 100. Negative signals
    (has-description / has-tests / scoped-diff) pull the score down so a
    well-formed PR rarely crosses the bar.
    """
    sigs = pr_signals(pr)
    risk = _clamp(sum(s.weight for s in sigs))
    pos = sum(s.weight for s in sigs if s.weight > 0)
    neg = sum(s.weight for s in sigs if s.weight < 0)
    needs = risk >= threshold
    return PRVerdict(
        number=pr.number,
        title=pr.title,
        html_url=pr.html_url,
        risk=risk,
        needs_review=needs,
        first_time=pr.first_time,
        signals=sigs,
        reason=_reason(needs, threshold, pos, neg),
    )


def batch(prs, threshold: float = _REVIEW_THRESHOLD) -> list:
    out = [triage_pr(p, threshold) for p in prs]
    out.sort(key=lambda v: (not v.needs_review, -v.risk, v.number))
    return out
